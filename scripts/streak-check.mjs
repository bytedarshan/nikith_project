import assert from 'node:assert/strict';
import {calculateStreak} from '../streaks.mjs';
import {plusDays} from '../seed.mjs';
const start='2026-11-01';
const days=n=>Array.from({length:n},(_,i)=>plusDays(start,i));
const check=(cond,label)=>{assert.ok(cond,label);console.log('✓ '+label)};
let r=calculateStreak([],start);
check(r.streak===0&&r.status==='new'&&r.shields===0,'New player has no fictional streak or shield');
r=calculateStreak(days(1),start);
check(r.streak===1&&r.status==='secured'&&r.bonusXp===0,'One five-round completion secures exactly one day');
r=calculateStreak(days(3),plusDays(start,2));
check(r.streak===3&&r.bonusXp===20&&r.todayBonusXp===20&&r.latestMilestone.name==='First Flame','Third consecutive completed day earns 20 XP once');
r=calculateStreak(days(7),plusDays(start,6));
check(r.streak===7&&r.shields===1&&r.bonusXp===70&&r.todayBonusXp===50,'Seven-day milestone earns one shield and 50 extra XP');
r=calculateStreak(days(7),plusDays(start,7));
check(r.streak===7&&r.status==='at-risk'&&r.shields===1,'Yesterday completer is warned rather than reset before playing');
r=calculateStreak(days(7),plusDays(start,8));
check(r.streak===7&&r.status==='shield-ready'&&r.shields===1,'One missed day can still be saved by earned shield');
r=calculateStreak([...days(7),plusDays(start,8)],plusDays(start,8));
check(r.streak===8&&r.shields===0&&r.shieldUsedToday,'Completing after one missed day uses the shield once and does not invent a completed day');
r=calculateStreak([...days(7),plusDays(start,9)],plusDays(start,9));
check(r.streak===1&&r.shields===1&&r.longest===7,'Two missed days break the streak without spending a shield');
r=calculateStreak(days(14),plusDays(start,13));
check(r.streak===14&&r.shields===1&&r.bonusXp===170&&r.todayBonusXp===100,'Day 14 adds next milestone XP and shield inventory stays capped at one');
r=calculateStreak(days(3),plusDays(start,7));
check(r.streak===0&&r.status==='restart'&&r.longest===3&&r.bonusXp===20,'Streak expiry retains earned historical XP and personal best');
r=calculateStreak([...days(7),plusDays(start,8),plusDays(start,8)],plusDays(start,8));
check(r.streak===8&&r.shields===0,'Duplicate completion dates never earn extra rewards');
console.log('\nAll V4 streak tests passed.');
